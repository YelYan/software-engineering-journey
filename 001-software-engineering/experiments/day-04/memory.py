name = "Yel Yan"
age = 25

print("Name:", name)
print("Age:", age)

print("Memory Address of Name:", id(name))
print("Memory Address of Age:", id(age))

# run python memory.py to execute this script

# id(name) → memory address of the object referenced by name, name → object in memory

# id(age) → memory address of the object referenced by age , age  → object in memory